#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKFLOW="$ROOT/.github/workflows/bootstrap-release-production.yml"
ACTIVATION_WORKFLOW="$ROOT/.github/workflows/bootstrap-release-activate.yml"
CONTINUITY_WORKFLOW="$ROOT/.github/workflows/bootstrap-release-continuity.yml"
RENEWAL_WORKFLOW="$ROOT/.github/workflows/bootstrap-release-renew.yml"
CLI="$ROOT/packages/control-plane/scripts/publish-release-to-r2.mjs"
ENV_SOURCE="$ROOT/packages/control-plane/src/env.ts"
POLICY="$ROOT/config/infisical/bootstrap-release-identities.json"
P=0 F=0
pass() { P=$((P + 1)); printf 'PASS %s\n' "$*"; }
fail() { F=$((F + 1)); printf 'FAIL %s\n' "$*" >&2; }
check() { description="$1"; shift; if "$@"; then pass "$description"; else fail "$description"; fi; }

test -f "$WORKFLOW" && test -f "$ACTIVATION_WORKFLOW" && test -f "$CONTINUITY_WORKFLOW" && test -f "$RENEWAL_WORKFLOW" || { printf 'missing production bootstrap release workflow\n' >&2; exit 1; }
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
sed -n '/^  build:/,/^  sign:/p' "$WORKFLOW" >"$tmp/build"
sed -n '/^  sign:/,/^  attest:/p' "$WORKFLOW" >"$tmp/sign"
sed -n '/^  attest:/,/^  publish:/p' "$WORKFLOW" >"$tmp/attest"
sed -n '/^  publish:/,$p' "$WORKFLOW" >"$tmp/publish"
sed -n '/^  activate:/,$p' "$ACTIVATION_WORKFLOW" >"$tmp/activate"
sed -n '/^  assemble:/,/^  prepare:/p' "$RENEWAL_WORKFLOW" >"$tmp/renew-assemble"
sed -n '/^  prepare:/,/^  sign:/p' "$RENEWAL_WORKFLOW" >"$tmp/renew-prepare"
sed -n '/^  sign:/,/^  publish:/p' "$RENEWAL_WORKFLOW" >"$tmp/renew-sign"
sed -n '/^  publish:/,/^  activate:/p' "$RENEWAL_WORKFLOW" >"$tmp/renew-publish"
sed -n '/^  activate:/,$p' "$RENEWAL_WORKFLOW" >"$tmp/renew-activate"

check 'release is manual-only' grep -q '^  workflow_dispatch:' "$WORKFLOW"
if grep -Eq '^  (push|pull_request|schedule):' "$WORKFLOW"; then fail 'release workflow has an automatic trigger'; else pass 'release workflow has no automatic trigger'; fi
check 'global token permissions default to none' grep -q '^permissions: {}' "$WORKFLOW"
check 'release serialization never cancels an in-flight release' grep -q 'cancel-in-progress: false' "$WORKFLOW"
check 'build is pinned to the canonical master ref' grep -q "github.ref == 'refs/heads/master'" "$tmp/build"
check 'build has source read permission' grep -q 'contents: read' "$tmp/build"
if grep -q 'id-token: write' "$tmp/build"; then fail 'build can mint an OIDC token'; else pass 'build cannot mint an OIDC token'; fi
check 'only the unprivileged build checks out source' grep -q 'actions/checkout@' "$tmp/build"
if grep -q '^  activate:' "$WORKFLOW"; then fail 'publication workflow still couples activation to regenerated bytes'; else pass 'publication and activation are separate dispatches'; fi

check 'signer uses its protected environment' grep -q 'environment: bootstrap-release-sign' "$tmp/sign"
check 'signer can mint only its short-lived OIDC token' grep -q 'id-token: write' "$tmp/sign"
if grep -q 'actions/checkout@' "$tmp/sign"; then fail 'signer checks out repository source'; else pass 'signer has no checkout'; fi
if grep -Eq 'actions/setup-node@|(^|[[:space:]])(npm|git|node)[[:space:]]' "$tmp/sign"; then fail 'signer executes repository build/runtime tooling'; else pass 'signer executes no repository build/runtime tooling'; fi
check 'signer executable is digest-pinned before execution' grep -q 'SIGNER_SCRIPT_SHA256.*sha256sum --check --strict' "$tmp/sign"
check 'signer fetches one exact Infisical leaf' grep -q 'secret-name: INSTALL_DOCTOR_RELEASE_SIGNING_KEY' "$tmp/sign"
check 'signer disables recursive/imported secret expansion' grep -q 'include-imports: false' "$tmp/sign"
check 'signer erases key material before artifact upload' grep -q 'INSTALL_DOCTOR_RELEASE_SIGNING_KEY=\\n' "$tmp/sign"

check 'attestor has only source-read and attestation token permissions' bash -c '
  grep -q "contents: read" "$1" &&
  grep -q "id-token: write" "$1" &&
  grep -q "attestations: write" "$1" &&
  grep -q "artifact-metadata: write" "$1"
' _ "$tmp/attest"
if grep -Eq 'Infisical|INSTALL_DOCTOR_RELEASE_SIGNING_KEY|publish-release-to-r2' "$tmp/attest"; then
  fail 'attestor has signing, secret-resolution, or publication authority'
else
  pass 'attestor has no signing, secret-resolution, or publication authority'
fi
check 'publication is gated on successful release attestations' grep -Fq 'needs: [build, sign, attest]' "$tmp/publish"

check 'publisher uses a separate protected environment' grep -q 'environment: bootstrap-release-publish' "$tmp/publish"
if grep -q 'actions/checkout@\|INSTALL_DOCTOR_RELEASE_SIGNING_KEY\|INSTALL_DOCTOR_CHANNEL_R2_' "$tmp/publish"; then
  fail 'publisher can access checkout, signing material, or channel authority'
else
  pass 'publisher has neither signing nor channel authority'
fi
if grep -Eq 'publish-release-to-r2\.mjs activate|release:activate' "$tmp/publish"; then fail 'publisher can activate a channel'; else pass 'publisher invokes no activation command'; fi
check 'activator uses a third protected environment' grep -q 'environment: bootstrap-release-activate' "$tmp/activate"
if grep -q 'actions/checkout@\|INSTALL_DOCTOR_RELEASE_SIGNING_KEY' "$tmp/activate"; then fail 'activator can access checkout or signing material'; else pass 'activator has no checkout or signing material'; fi
if grep -Eq 'publish-release-to-r2\.mjs publish|release:publish' "$tmp/activate"; then fail 'activator can publish release objects'; else pass 'activator invokes no publication command'; fi
check 'activation is an independent manual workflow' grep -q '^  workflow_dispatch:' "$ACTIVATION_WORKFLOW"
check 'activation requires an expected ETag' grep -q 'EXPECTED_ETAG' "$tmp/activate"
check 'activation blocks on public launcher and signature proof' grep -q 'ssh-keygen -Y verify' "$tmp/activate"
check 'activation reconciles a committed pending receipt without repeating CAS' grep -q 'publish-release-to-r2.mjs reconcile stable' "$tmp/activate"
check 'continuity monitor runs every six hours' grep -q "cron: '17 \*/6 \* \* \*'" "$CONTINUITY_WORKFLOW"
check 'continuity monitor uses a dedicated protected identity' grep -q 'environment: bootstrap-release-monitor' "$CONTINUITY_WORKFLOW"
if grep -Eq 'INSTALL_DOCTOR_RELEASE_SIGNING_KEY|publish-release-to-r2\.mjs (publish|activate)' "$CONTINUITY_WORKFLOW"; then
  fail 'continuity monitor has signing, publication, or activation authority'
else
  pass 'continuity monitor is read-only'
fi
check 'continuity monitor fails inside the 96-hour renewal window' grep -q 'freshness stable 345600' "$CONTINUITY_WORKFLOW"

check 'renewal is manual-only and shares the activation lock' grep -q '^  workflow_dispatch:' "$RENEWAL_WORKFLOW"
check 'renewal retries bind a caller-selected canonical UTC day' grep -q 'renewal_utc_day' "$RENEWAL_WORKFLOW"
# shellcheck disable=SC2016
check 'renewal assembly alone checks out source and cannot mint OIDC' bash -c '! grep -q "id-token: write" "$1" && grep -q "actions/checkout@" "$1"' _ "$tmp/renew-assemble"
check 'renewal preparation uses a dedicated read-only protected identity' grep -q 'environment: bootstrap-release-renew-prepare' "$tmp/renew-prepare"
if grep -Eq 'publish-release-to-r2\.mjs (publish|activate|activate-renewal)|INSTALL_DOCTOR_RELEASE_SIGNING_KEY' "$tmp/renew-prepare"; then fail 'renewal preparer has mutation or signing behavior'; else pass 'renewal preparer invokes only read/prepare behavior'; fi
# shellcheck disable=SC2016
check 'renewal preserves the freshness command exit status exactly once' bash -c 'test "$(grep -Fc "freshness_status=\$?" "$1")" -eq 1' _ "$tmp/renew-prepare"
check 'renewal signer uses a dedicated protected no-checkout environment' grep -q 'environment: bootstrap-release-renew-sign' "$tmp/renew-sign"
if grep -Eq 'actions/checkout@|actions/setup-node@|(^|[[:space:]])(npm|git|node)[[:space:]]' "$tmp/renew-sign"; then fail 'renewal signer executes checkout or repository build/runtime tooling'; else pass 'renewal signer executes no checkout or repository build/runtime tooling'; fi
# shellcheck disable=SC2016
check 'renewal signer is digest-pinned before secret resolution' bash -c 'pin=$(grep -n "sha256sum --check --strict" "$1" | head -1 | cut -d: -f1); secret=$(grep -n "Infisical/secrets-action@" "$1" | head -1 | cut -d: -f1); test -n "$pin" && test -n "$secret" && test "$pin" -lt "$secret"' _ "$tmp/renew-sign"
check 'renewal signer fetches exactly one secret without imports or recursion' grep -q 'secret-name: INSTALL_DOCTOR_RELEASE_SIGNING_KEY' "$tmp/renew-sign"
check 'renewal publisher uses workflow-bound immutable release-only authority' grep -q 'environment: bootstrap-release-renew-publish' "$tmp/renew-publish"
if grep -Eq 'INSTALL_DOCTOR_RELEASE_SIGNING_KEY|INSTALL_DOCTOR_CHANNEL_R2_|publish-release-to-r2\.mjs (activate|activate-renewal)' "$tmp/renew-publish"; then fail 'renewal publisher has signing or channel authority'; else pass 'renewal publisher has neither signing nor channel authority'; fi
check 'renewal activation uses the constrained command' grep -q 'publish-release-to-r2.mjs activate-renewal' "$tmp/renew-activate"
check 'renewal activation uses a workflow-bound protected activator' grep -q 'environment: bootstrap-release-renew-activate' "$tmp/renew-activate"
if grep -Eq 'INSTALL_DOCTOR_RELEASE_SIGNING_KEY|publish-release-to-r2\.mjs publish' "$tmp/renew-activate"; then fail 'renewal activator has signing or publication behavior'; else pass 'renewal activator has no signing or publication behavior'; fi
check 'renewal activation blocks on public signature proof' grep -q 'ssh-keygen -Y verify' "$tmp/renew-activate"

check 'publisher CLI uses release-bucket credentials' grep -q "storageFromEnvironment('INSTALL_DOCTOR_RELEASE_R2')" "$CLI"
check 'activator CLI uses a distinct channel bucket' grep -q "storageFromEnvironment('INSTALL_DOCTOR_CHANNEL_R2')" "$CLI"
check 'Worker declares a distinct channel binding' grep -q 'RELEASE_CHANNELS:' "$ENV_SOURCE"
check 'shared value-free Infisical workload identity policy validates' node "$ROOT/scripts/infisical-identity-policy.mjs" validate "$POLICY"
check 'promotion verifier has an exact read-only OIDC identity' jq -e '
  [.workloads[] | select(.id == "github-platform-promotion-reader")] | length == 1 and
  .[0].auth.claims.environment == "platform-promotion-verifier" and
  .[0].auth.claims.workflow_ref == "heymegabyte/install.doctor/.github/workflows/platform-promotion-verifier.yml@refs/heads/master" and
  .[0].authorization.path == "/ci/offline-bundle/promotion-read" and
  .[0].authorization.inheritedGrants == []
' "$POLICY"
check 'every release identity binds immutable repository IDs and an exact workflow ref' jq -e 'all(.workloads[]; .auth.claims.repository_id == "588807533" and .auth.claims.repository_owner_id == "82490183" and (.auth.claims.workflow_ref | test("^heymegabyte/install\\.doctor/\\.github/workflows/[a-z0-9._-]+\\.yml@refs/heads/master$")))' "$POLICY"
check 'Worker trust is sourced from the versioned trust manifest' grep -q "import trust from './release-trust.json'" "$ROOT/packages/control-plane/src/release-keyring.ts"
if jq -e '
  .schemaVersion == 2 and (.products | keys == ["desktop-tools","legacy-install-doctor"]) and
  .products["desktop-tools"].origin == "https://desktop.tools" and
  .products["desktop-tools"].signatureNamespace == "desktop.tools.release" and
  .products["legacy-install-doctor"].origin == "https://app.install.doctor" and
  .products["legacy-install-doctor"].signatureNamespace == "install.doctor.release" and
  (all(.products[]; (.signers | type == "object") and
    ([.signers | to_entries[] | select((.key | test("^[a-z0-9][a-z0-9._-]{0,127}$") | not) or (.value | test("^ssh-ed25519 [A-Za-z0-9+/]+={0,3}( [^[:cntrl:]]{1,128})?$") | not))] | length == 0)))
' "$ROOT/packages/control-plane/src/release-trust.json" >/dev/null; then pass 'versioned release trust manifest is strict'; else fail 'release trust manifest is malformed'; fi
if grep -q 'secrets\.' "$WORKFLOW" "$ACTIVATION_WORKFLOW" "$CONTINUITY_WORKFLOW" "$RENEWAL_WORKFLOW"; then fail 'workflow consumes long-lived GitHub Actions secrets'; else pass 'workflow has no GitHub Actions secret dependency'; fi

printf 'bootstrap-release-workflow: %d passed, %d failed\n' "$P" "$F"
[ "$F" -eq 0 ]
